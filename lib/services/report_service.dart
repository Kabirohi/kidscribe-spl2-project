import 'dart:io';
import 'package:path_provider/path_provider.dart';
import '../data/trace_templates.dart';
import '../data/word_list.dart';
import 'progress_service.dart';

/// Builds and saves a progress report file for one learner
/// (SRS US_24: teachers export it for parent meetings).
class ReportService {
  final ProgressService _progress = ProgressService();

  /// Creates the report and writes it to a .txt file in the app's
  /// documents folder. Returns (file path, report text).
  Future<(String, String)> exportReport({
    required String displayName,
    required String scope,
  }) async {
    final content = await buildReport(displayName: displayName, scope: scope);

    final dir = await getApplicationDocumentsDirectory();
    final safeName = displayName.trim().replaceAll(RegExp(r'[^\w]+'), '_');
    final now = DateTime.now();
    final stamp =
        '${now.year}-${now.month.toString().padLeft(2, '0')}-${now.day.toString().padLeft(2, '0')}';
    final file = File('${dir.path}/KidScribe_report_${safeName}_$stamp.txt');
    await file.writeAsString(content);
    return (file.path, content);
  }

  Future<String> buildReport({
    required String displayName,
    required String scope,
  }) async {
    final summary = await _progress.summarizeScope(scope);
    final now = DateTime.now();
    final b = StringBuffer()
      ..writeln('KidScribe — Progress Report')
      ..writeln('Learner: $displayName')
      ..writeln('Date: ${now.day}/${now.month}/${now.year}')
      ..writeln('----------------------------------------');

    // SRS T_58: a learner with no activity gets a clear note.
    if (!summary.hasActivity) {
      b
        ..writeln('No activity yet.')
        ..writeln('')
        ..writeln('$displayName has not started practicing. '
            'Open "Start Learning" and try Stage 1 together!');
      return b.toString();
    }

    final letters = await _progress.loadLettersFor(scope);
    final words = await _progress.loadWordsFor(scope);

    b
      ..writeln(
          'Stage 1 - Strokes : ${summary.strokesDone} / ${stage1Items.length}')
      ..writeln(
          'Stage 2 - Letters : ${summary.lettersDone} / ${allLetterItems.length}')
      ..writeln(
          'Stage 3 - Words   : ${summary.wordsDone} / ${practiceWords.length}')
      ..writeln('Total practice checks: ${summary.totalChecks}');
    if (summary.lastPractice != null) {
      final d = summary.lastPractice!;
      b.writeln('Last practiced: ${d.day}/${d.month}/${d.year}');
    }

    final done = <String>[];
    final weak = <String>[];
    for (final item in allLetterItems) {
      final e = letters[item.glyph];
      if (ProgressService.letterComplete(e)) {
        done.add(item.glyph);
      } else if (e != null &&
          ((e['guided'] ?? 0) > 0 || (e['free'] ?? 0) > 0)) {
        final free = e['free'] ?? 0;
        weak.add(free > 0
            ? '${item.glyph} (free-hand $free%)'
            : '${item.glyph} (free-hand not tried)');
      }
    }

    b.writeln('----------------------------------------');
    b.writeln(
        'Finished letters: ${done.isEmpty ? 'none yet' : done.join(' ')}');
    final finishedWords =
        practiceWords.where((w) => words.containsKey(w.word)).map((w) => w.word);
    b.writeln(
        'Finished words: ${finishedWords.isEmpty ? 'none yet' : finishedWords.join(', ')}');
    if (weak.isNotEmpty) {
      b
        ..writeln('Needs practice:')
        ..writeln('  ${weak.join('\n  ')}');
    }

    b
      ..writeln('----------------------------------------')
      ..writeln('Generated by KidScribe (SPL Group 18, IUT).');
    return b.toString();
  }
}
